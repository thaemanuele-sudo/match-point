/** Sostituisce i segnaposto {nome} nei testi del dizionario. */
export function fmt(s: string, v: Record<string, string | number> = {}): string {
  return s.replace(/\{(\w+)\}/g, (_, k: string) => (k in v ? String(v[k]) : `{${k}}`));
}
